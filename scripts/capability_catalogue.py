"""Generate/check H07 catalogue inputs without modifying the DOM generator."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]

def generate():
    model = json.loads((ROOT/'gen/dom-api.json').read_text())
    names = ['dom-generated'] + ['dom:' + item['name'] for item in model['interfaces']]
    for function in model['functions']:
        if function.get('feature'): names.append(function['feature'])
    for item in model['runtimeTypeQueries']:
        if item.get('feature'): names.append(item['feature'])
    glue = (ROOT/'host/dom/RanvierDomGlue.cpp').read_text()
    has = glue.split('int32_t ranvier_dom_has(',1)[1].split('\n}',1)[0]
    names += re.findall(r'"(dom[^"\n]+)"', has)
    host = (ROOT/'host/RanvierWebCoreAbi.cpp').read_text().split('int32_t rv_abi_has(',1)[1].split('\n}',1)[0]
    names += re.findall(r'"([^"\n]+)"', re.sub(r'//[^\n]*', '', host))
    names += ['capabilities']
    flags = set()
    for path in (ROOT/'config').glob('*.cmake'):
        flags.update(re.findall(r'set\(((?:USE|ENABLE)_[A-Z0-9_]+)\s+(?:ON|OFF)\s+CACHE BOOL',path.read_text()))
    # Current facilities whose port defaults also affect the selected H07 scope.
    flags.update(['ENABLE_WEBGPU','ENABLE_WEBXR','ENABLE_MEDIA_STREAM','ENABLE_MEDIA_RECORDER','ENABLE_WEB_CODECS','ENABLE_WEB_AUDIO','ENABLE_ENCRYPTED_MEDIA','ENABLE_WEB_RTC','ENABLE_NOTIFICATIONS','ENABLE_ACCESSIBILITY','ENABLE_FONT_LOADING','USE_WOFF2'])
    output = ['// Generated by scripts/capability_catalogue.py from the ABI model and profile switches.',
              'static constexpr const char* capabilityAbiNames[] = {']
    output += ['    '+json.dumps(name)+',' for name in dict.fromkeys(names)]
    output += ['};', 'static constexpr CapabilityBuildFlag capabilityBuildFlags[] = {']
    for flag in sorted(flags):
        output += ['#if defined(RV_CAP_'+flag+')', '    {"build:'+flag+'", RV_CAP_'+flag+'},', '#elif defined('+flag+')', '    {"build:'+flag+'", '+flag+'},', '#else', '    {"build:'+flag+'", -1},', '#endif']
    output += ['};','']
    return '\n'.join(output)

if __name__ == '__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    target=ROOT/'host/RanvierCapabilityCatalogue.inc'
    expected=generate()
    if args.check:
        assert target.read_text() == expected, 'Capability catalogue is stale'
        print('CAPABILITY_CATALOGUE_CHECK=PASS')
    else:
        target.write_text(expected)
